import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsBoolean,
  IsDateString,
  IsEmail,
  IsIn,
  IsInt,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  IsUUID,
  Max,
  Min,
  ValidateNested,
} from 'class-validator';

/**
 * Payload of ONE capture window sent by the Meet extension
 * (POST /engagement/frames). Mirrors offscreen.js#finalizeWindow +
 * background.js exactly - with the global ValidationPipe running
 * `forbidNonWhitelisted`, every field the extension sends must be declared.
 *
 * Shape checks that class-validator can't express (base64 byte length,
 * [16][52][3] landmarks, consistency between fields) are business rules in
 * WindowValidator.
 */

export class CropBoxDto {
  @IsIn(['face', 'center'])
  source!: 'face' | 'center';

  @IsNumber()
  x!: number;

  @IsNumber()
  y!: number;

  @IsNumber()
  @Min(0)
  size!: number;

  @IsInt()
  @Min(1)
  frameWidth!: number;

  @IsInt()
  @Min(1)
  frameHeight!: number;
}

export class FrameTimingDto {
  @IsNumber()
  meshMs!: number;

  @IsNumber()
  cropMs!: number;

  @IsNumber()
  totalMs!: number;
}

export class WindowTimingDto {
  @IsNumber()
  avgFrameMs!: number;

  @IsNumber()
  maxFrameMs!: number;

  @IsNumber()
  avgMeshMs!: number;

  @IsNumber()
  encodeMs!: number;

  @IsNumber()
  windowSpanMs!: number;
}

export class FrameItemDto {
  @IsInt()
  @Min(0)
  index!: number;

  @IsOptional()
  @IsDateString()
  capturedAt!: string | null;

  @IsBoolean()
  faceDetected!: boolean;

  @IsOptional()
  @ValidateNested()
  @Type(() => CropBoxDto)
  cropBox!: CropBoxDto | null;

  @IsOptional()
  @ValidateNested()
  @Type(() => FrameTimingDto)
  timingMs!: FrameTimingDto | null;

  @IsIn(['base64'])
  encoding!: 'base64';

  @IsIn(['uint8'])
  dtype!: 'uint8';

  @IsArray()
  @ArrayMinSize(3)
  @ArrayMaxSize(3)
  @IsInt({ each: true })
  shape!: [number, number, number];

  @IsIn(['RGB'])
  channelOrder!: 'RGB';

  @IsString()
  @IsNotEmpty()
  data!: string;
}

export class FrameDTO {
  /** Generated by the extension per recording (crypto.randomUUID()). */
  @IsUUID()
  sessionId!: string;

  @IsOptional()
  @IsString()
  meetingId!: string | null;

  @IsInt()
  @Min(0)
  windowIndex!: number;

  @IsDateString()
  startedAt!: string;

  @IsDateString()
  endedAt!: string;

  @IsBoolean()
  partial!: boolean;

  @IsInt()
  @Min(0)
  @Max(256)
  framesFilled!: number;

  @IsNumber()
  frameIntervalMs!: number;

  @IsArray()
  @IsBoolean({ each: true })
  faceDetected!: boolean[];

  @ValidateNested()
  @Type(() => WindowTimingDto)
  timing!: WindowTimingDto;

  /** [frames][52][3], normalised to the full camera frame; zeros where no face. */
  @IsArray()
  landmarks!: number[][][];

  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => FrameItemDto)
  frames!: FrameItemDto[];

  @IsOptional()
  @IsEmail({}, { message: 'userEmail must be an email' })
  userEmail!: string | null;

  @IsOptional()
  @IsString()
  userName!: string | null;

  /** Google account id ("sub"), or "dev" in DEV_SKIP_LOGIN mode. */
  @IsOptional()
  @IsString()
  userId!: string | null;

  @IsArray()
  @IsInt({ each: true })
  landmarkIndices!: number[];

  @IsInt()
  landmarkCount!: number;
}
